function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function resultPath(cwd: string, relativePath: string): string {
  return path.join(cwd, relativePath);
}

function backupFileIfNeeded(filePath: string): { path: string; created: boolean } {
  const backupPath = `${filePath}.bak`;
  if (!fs.existsSync(backupPath)) {
    fs.copyFileSync(filePath, backupPath);
    return { path: backupPath, created: true };
  }
  return { path: backupPath, created: false };
}

function removeEmptyParents(cwd: string, startDir: string): void {
  const root = path.resolve(cwd);
  let current = path.resolve(startDir);
  while (current !== root && current.startsWith(`${root}${path.sep}`)) {
    try {
      fs.rmdirSync(current);
    } catch {
      return;
    }
    current = path.dirname(current);
  }
}

function removePath(
  cwd: string,
  relativePath: string,
  opts: ClearOptions,
  message: string,
  backup = false,
): ClearResult {
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  if (opts.dryRun) {
    return { path: filePath, status: 'would-remove', message };
  }

  const backupResult = backup && fs.statSync(filePath).isFile()
    ? backupFileIfNeeded(filePath)
    : undefined;
  fs.rmSync(filePath, { recursive: true, force: true });
  removeEmptyParents(cwd, path.dirname(filePath));
  return {
    path: filePath,
    status: 'removed',
    backupPath: backupResult?.path,
    backupCreated: backupResult?.created,
    message,
  };
}

function removeExactGeneratedFile(
  cwd: string,
  relativePath: string,
  opts: ClearOptions,
  message: string,
  expectedContent: string,
): ClearResult {
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }
  if (!fs.statSync(filePath).isFile()) {
    return { path: filePath, status: 'skipped', message: 'not a file' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // EOL-insensitive compare only for uniform-EOL files; a mixed-EOL file must
  // match the template byte-exact, otherwise it counts as modified.
  const matchesTemplate = isUniformEol(current)
    ? normalizeEol(current) === normalizeEol(expectedContent)
    : current === expectedContent;
  if (!matchesTemplate) {
    return { path: filePath, status: 'skipped', message: 'modified or not generated by known repovine templates' };
  }

  return removePath(cwd, relativePath, opts, message);
}

function writeOrRemoveText(
  cwd: string,
  relativePath: string,
  nextContent: string,
  opts: ClearOptions,
  message: string,
  removeWhenEmpty = true,
  eol: Eol | null = '\n',
): ClearResult {
  const filePath = resultPath(cwd, relativePath);
  const shouldRemove = removeWhenEmpty && nextContent.trim() === '';

  if (opts.dryRun) {
    return {
      path: filePath,
      status: shouldRemove ? 'would-remove' : 'would-update',
      message,
    };
  }

  const backupResult = backupFileIfNeeded(filePath);
  if (shouldRemove) {
    fs.rmSync(filePath, { force: true });
    removeEmptyParents(cwd, path.dirname(filePath));
    return {
      path: filePath,
      status: 'removed',
      backupPath: backupResult.path,
      backupCreated: backupResult.created,
      message,
    };
  }

  // `eol: null` writes nextContent verbatim; used for mixed-EOL files where
  // applyEol would homogenize newlines outside the managed content.
  fs.writeFileSync(filePath, eol === null ? nextContent : applyEol(nextContent, eol), 'utf-8');
  return {
    path: filePath,
    status: 'updated',
    backupPath: backupResult.path,
    backupCreated: backupResult.created,
    message,
  };
}

function removeMcpJsonServer(
  cwd: string,
  relativePath: string,
  templateContent: string,
  opts: ClearOptions,
): ClearResult {
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // Mixed-EOL files compare byte-exact and are rewritten as LF JSON verbatim.
  const uniform = isUniformEol(current);
  const eol = uniform ? detectEol(current) : null;
  const matchesTemplate = uniform
    ? normalizeEol(current) === normalizeEol(templateContent)
    : current === templateContent;
  if (matchesTemplate) {
    return removePath(cwd, relativePath, opts, 'remove generated MCP config');
  }

  let parsed: Record<string, unknown>;
  try {
    const raw = JSON.parse(current) as unknown;
    if (!isRecord(raw)) {
      return { path: filePath, status: 'error', message: 'expected JSON object' };
    }
    parsed = raw;
  } catch (e) {
    return { path: filePath, status: 'error', message: `could not parse JSON: ${(e as Error).message}` };
  }

  const servers = parsed.mcpServers;
  if (!isRecord(servers)) {
    return { path: filePath, status: 'skipped', message: 'repovine MCP server not present' };
  }

  const nextServers = { ...servers };
  const removedServers = Object.keys(nextServers).filter(name => MANAGED_MCP_SERVER_NAMES.has(name));
  if (removedServers.length === 0) {
    return { path: filePath, status: 'skipped', message: 'repovine MCP server not present' };
  }

  for (const name of removedServers) {
    delete nextServers[name];
  }
  const next = { ...parsed };
  if (Object.keys(nextServers).length === 0) {
    delete next.mcpServers;
  } else {
    next.mcpServers = nextServers;
  }

  const nextContent = Object.keys(next).length === 0
    ? ''
    : `${JSON.stringify(next, null, 2)}\n`;
  return writeOrRemoveText(cwd, relativePath, nextContent, opts, 'remove repovine MCP server and preserve other settings', true, eol);
}

function removeCursorHooksJson(cwd: string, opts: ClearOptions): ClearResult {
  const relativePath = path.join('.cursor', 'hooks.json');
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // Mixed-EOL files compare byte-exact and are rewritten as LF JSON verbatim.
  const uniform = isUniformEol(current);
  const eol = uniform ? detectEol(current) : null;
  // Pristine generated files are removed whole; anything else takes the entry-level path.
  const generatedForms = [`${JSON.stringify(CURSOR_HOOKS_SETTINGS, null, 2)}\n`];
  const matchesGenerated = generatedForms.some(generated =>
    uniform ? normalizeEol(current) === generated : current === generated);
  if (matchesGenerated) {
    return removePath(cwd, relativePath, opts, 'remove generated Cursor hooks config');
  }

  let parsed: Record<string, unknown>;
  try {
    const raw = JSON.parse(current) as unknown;
    if (!isRecord(raw)) {
      return { path: filePath, status: 'error', message: 'expected JSON object' };
    }
    parsed = raw;
  } catch (e) {
    return { path: filePath, status: 'error', message: `could not parse JSON: ${(e as Error).message}` };
  }

  const hooks = parsed.hooks;
  if (!isRecord(hooks)) {
    return { path: filePath, status: 'skipped', message: 'Cursor hooks object not present' };
  }

  const nextHooks: Record<string, unknown> = {};
  let changed = false;
  for (const [eventName, entries] of Object.entries(hooks)) {
    if (!Array.isArray(entries)) {
      nextHooks[eventName] = entries;
      continue;
    }
    const kept = entries.filter(entry =>
      !(isRecord(entry) && isManagedCursorHookCommand(entry.command)));
    if (kept.length !== entries.length) changed = true;
    if (kept.length > 0) nextHooks[eventName] = kept;
  }

  if (!changed) {
    return { path: filePath, status: 'skipped', message: 'repovine Cursor hooks not present' };
  }

  const next = { ...parsed };
  if (Object.keys(nextHooks).length === 0) {
    delete next.hooks;
  } else {
    next.hooks = nextHooks;
  }

  const nextContent = Object.keys(next).length === 0 || (Object.keys(next).length === 1 && next.version === 1)
    ? ''
    : `${JSON.stringify(next, null, 2)}\n`;
  return writeOrRemoveText(cwd, relativePath, nextContent, opts, 'remove repovine Cursor hooks and preserve unrelated hooks/settings', true, eol);
}

function removeClaudeSettingsJson(cwd: string, opts: ClearOptions): ClearResult {
  const relativePath = path.join('.claude', 'settings.json');
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // Mixed-EOL files compare byte-exact and are rewritten as LF JSON verbatim.
  const uniform = isUniformEol(current);
  const eol = uniform ? detectEol(current) : null;
  // Pristine generated files reduce to an empty settings object; anything else
  // takes the hook-level path.
  const generatedForms = [`${JSON.stringify({ hooks: CLAUDE_HOOKS_SETTINGS }, null, 2)}\n`];
  const matchesGenerated = generatedForms.some(generated =>
    uniform ? normalizeEol(current) === generated : current === generated);
  if (matchesGenerated) {
    return writeOrRemoveText(
      cwd,
      relativePath,
      EMPTY_JSON_OBJECT,
      opts,
      'remove repovine Claude hooks and preserve Claude settings file',
      false,
      eol,
    );
  }

  let parsed: Record<string, unknown>;
  try {
    const raw = JSON.parse(current) as unknown;
    if (!isRecord(raw)) {
      return { path: filePath, status: 'error', message: 'expected JSON object' };
    }
    parsed = raw;
  } catch (e) {
    return { path: filePath, status: 'error', message: `could not parse JSON: ${(e as Error).message}` };
  }

  const hooks = parsed.hooks;
  if (!isRecord(hooks)) {
    return { path: filePath, status: 'skipped', message: 'Claude hooks object not present' };
  }

  const nextHooks: Record<string, unknown> = {};
  let changed = false;
  for (const [eventName, entries] of Object.entries(hooks)) {
    if (!Array.isArray(entries)) {
      nextHooks[eventName] = entries;
      continue;
    }
    const keptEntries = entries
      .map(entry => {
        if (!isRecord(entry) || !Array.isArray(entry.hooks)) return entry;
        const keptHooks = entry.hooks.filter(hook => !isManagedClaudeHook(hook));
        if (keptHooks.length !== entry.hooks.length) changed = true;
        return keptHooks.length > 0 ? { ...entry, hooks: keptHooks } : undefined;
      })
      .filter((entry): entry is unknown => entry !== undefined);
    if (keptEntries.length > 0) nextHooks[eventName] = keptEntries;
  }

  if (!changed) {
    return { path: filePath, status: 'skipped', message: 'repovine Claude hooks not present' };
  }

  const next = { ...parsed };
  if (Object.keys(nextHooks).length === 0) {
    delete next.hooks;
  } else {
    next.hooks = nextHooks;
  }

  const nextContent = Object.keys(next).length === 0 ? EMPTY_JSON_OBJECT : `${JSON.stringify(next, null, 2)}\n`;
  return writeOrRemoveText(
    cwd,
    relativePath,
    nextContent,
    opts,
    'remove repovine Claude hooks and preserve Claude settings file',
    false,
    eol,
  );
}

function removeAgentsMd(cwd: string, opts: ClearOptions): ClearResult {
  const relativePath = 'AGENTS.md';
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // Mixed-EOL files stay byte-exact: markers are searched and sliced in the
  // raw bytes and the result is written verbatim.
  const uniform = isUniformEol(current);
  const eol = uniform ? detectEol(current) : null;
  const normalized = uniform ? normalizeEol(current) : current;
  if (normalized === AGENTS_MD) {
    return removePath(cwd, relativePath, opts, 'remove generated AGENTS.md');
  }

  const begin = normalized.indexOf(AGENTS_MD_BEGIN_MARKER);
  const end = normalized.indexOf(AGENTS_MD_END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    return { path: filePath, status: 'skipped', message: 'repovine AGENTS.md section not found' };
  }

  const sectionEnd = end + AGENTS_MD_END_MARKER.length;
  const before = normalized.slice(0, begin).trimEnd();
  const after = normalized.slice(sectionEnd).trimStart();
  const nextContent = [before, after].filter(Boolean).join('\n\n');
  return writeOrRemoveText(
    cwd,
    relativePath,
    nextContent ? `${nextContent}\n` : '',
    opts,
    'remove repovine AGENTS.md section and preserve other instructions',
    true,
    eol,
  );
}

function removeGitignoreBlock(cwd: string, opts: ClearOptions): ClearResult {
  const relativePath = '.gitignore';
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const current = fs.readFileSync(filePath, 'utf-8');
  // Mixed-EOL files are written as LF verbatim; the line pipeline is lossy for
  // them, so no single EOL can be restored faithfully.
  const eol = isUniformEol(current) ? detectEol(current) : null;
  const lines = current.split(/\r?\n/);
  const nextLines: string[] = [];
  let changed = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? '';
    if (!GITIGNORE_HEADERS.has(line.trim())) {
      nextLines.push(line);
      continue;
    }

    changed = true;
    i++;
    while (i < lines.length) {
      const candidate = lines[i] ?? '';
      if (candidate.trim() === '' || GITIGNORE_ENTRIES.has(candidate.trim())) {
        i++;
        continue;
      }
      i--;
      break;
    }
  }

  if (!changed) {
    return { path: filePath, status: 'skipped', message: 'repovine gitignore block not found' };
  }

  const nextContent = nextLines.join('\n').trim() ? `${nextLines.join('\n').replace(/\n+$/u, '')}\n` : '';
  return writeOrRemoveText(cwd, relativePath, nextContent, opts, 'remove repovine cache entries from .gitignore', true, eol);
}

function removeCodexHooksBlock(content: string): { content: string; changed: boolean } {
  const beginIndex = content.indexOf(CODEX_HOOKS_BEGIN_MARKER);
  const endIndex = content.indexOf(CODEX_HOOKS_END_MARKER);
  if (beginIndex === -1 || endIndex === -1 || endIndex < beginIndex) {
    return { content, changed: false };
  }

  let blockStart = content.lastIndexOf('\n', beginIndex);
  blockStart = blockStart >= 0 ? blockStart + 1 : 0;

  const previousLineEnd = Math.max(0, blockStart - 1);
  const previousLineStart = content.lastIndexOf('\n', previousLineEnd - 1) + 1;
  const previousLine = content.slice(previousLineStart, previousLineEnd);
  if (/^\s*# repovine hooks/u.test(previousLine)) {
    blockStart = previousLineStart;
  }

  let blockEnd = endIndex + CODEX_HOOKS_END_MARKER.length;
  if (content[blockEnd] === '\n') blockEnd++;

  const before = content.slice(0, blockStart).trimEnd();
  const after = content.slice(blockEnd).trimStart();
  return {
    content: [before, after].filter(Boolean).join('\n\n') + (before || after ? '\n' : ''),
    changed: true,
  };
}

function isTomlTableHeader(line: string): boolean {
  return /^\s*\[{1,2}[^\]]+\]{1,2}\s*$/u.test(line);
}

function trimCtxmorphMcpComment(lines: string[]): void {
  const blanks: string[] = [];
  while (lines.length > 0 && (lines[lines.length - 1] ?? '').trim() === '') {
    blanks.push(lines.pop() ?? '');
  }

  const previous = lines[lines.length - 1] ?? '';
  if (/^\s*# repovine MCP/u.test(previous)) {
    lines.pop();
    return;
  }

  while (blanks.length > 0) {
    lines.push(blanks.pop() ?? '');
  }
}

function removeCodexMcpSections(content: string): { content: string; changed: boolean } {
  const lines = content.split(/\r?\n/);
  const next: string[] = [];
  let skipping = false;
  let changed = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (/^\[mcp_servers\.repovine(?:\.|\])/u.test(trimmed)) {
      if (!skipping) trimCtxmorphMcpComment(next);
      skipping = true;
      changed = true;
      continue;
    }

    if (skipping && isTomlTableHeader(line)) {
      skipping = false;
    }

    if (!skipping) next.push(line);
  }

  if (!changed) return { content, changed: false };
  const nextContent = next.join('\n').replace(/\n{3,}/gu, '\n\n').trim();
  return { content: nextContent ? `${nextContent}\n` : '', changed: true };
}

function hasOnlyGeneratedCodexRemainder(content: string): boolean {
  const meaningful = content
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(line => line.length > 0 && !line.startsWith('#'))
    .filter(line => line !== 'project_doc_max_bytes = 65536');
  return meaningful.length === 0;
}

function removeCodexConfig(cwd: string, opts: ClearOptions): ClearResult {
  const relativePath = path.join('.codex', 'config.toml');
  const filePath = resultPath(cwd, relativePath);
  if (!fs.existsSync(filePath)) {
    return { path: filePath, status: 'skipped', message: 'not found' };
  }

  const raw = fs.readFileSync(filePath, 'utf-8');
  // The marker/slice pipeline assumes LF; the write restores the file's EOL.
  // Mixed-EOL files skip normalization and are written verbatim, so bytes
  // outside the removed sections keep their newlines.
  const uniform = isUniformEol(raw);
  const eol = uniform ? detectEol(raw) : null;
  const current = uniform ? normalizeEol(raw) : raw;
  const withoutHooks = removeCodexHooksBlock(current);
  const withoutMcp = removeCodexMcpSections(withoutHooks.content);
  if (!withoutHooks.changed && !withoutMcp.changed) {
    return { path: filePath, status: 'skipped', message: 'repovine Codex sections not found' };
  }

  const nextContent = hasOnlyGeneratedCodexRemainder(withoutMcp.content)
    ? PRESERVED_CODEX_CONFIG_TOML
    : withoutMcp.content;
  return writeOrRemoveText(
    cwd,
    relativePath,
    nextContent,
    opts,
    'remove repovine Codex MCP/hooks and preserve Codex config file',
    false,
    eol,
  );
}

function renderedAssetPath(asset: OnboardingAsset, target: RenderedAssetTarget): string {
  if (target.fileName) {
    return path.join(target.relativeDir, asset.name, target.fileName);
  }
  if (!target.extension) {
    throw new Error('Rendered asset target requires either extension or fileName');
  }
  return path.join(target.relativeDir, `${asset.name}.${target.extension}`);
}

function addRenderedAssets(
  files: Map<string, GeneratedFile>,
  assets: OnboardingAsset[],
  target: RenderedAssetTarget,
): void {
  for (const asset of assets) {
    const relativePath = renderedAssetPath(asset, target);
    files.set(relativePath, { relativePath });
  }
}


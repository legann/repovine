export type ClearStatus =
  | 'would-remove'
  | 'would-update'
  | 'removed'
  | 'updated'
  | 'skipped'
  | 'error';

export interface ClearResult {
  path: string;
  status: ClearStatus;
  backupPath?: string;
  backupCreated?: boolean;
  message?: string;
}

export interface ClearOptions {
  dryRun: boolean;
}

export interface RunClearOptions {
  /** Print the plan and exit without asking. */
  dryRun?: boolean;
  /** Skip the confirmation prompt and apply. */
  yes?: boolean;
  /** Test hook for the interactive confirmation. */
  confirm?: () => boolean | Promise<boolean>;
}


function printResultGroup(
  cwd: string,
  label: string,
  results: ClearResult[],
  status: ClearStatus,
  tone: FileResultTone,
): void {
  const group = results.filter(r => r.status === status);
  if (group.length === 0) return;
  console.log(formatGroupLabel(label, tone));
  for (const r of group) {
    const rel = path.relative(cwd, r.path);
    console.log(formatFileLine(tone, rel, {
      backup: r.backupPath ? path.relative(cwd, r.backupPath) : undefined,
      note: r.message,
      noteSeparator: ' - ',
    }));
  }
}

function hasPlannedChanges(results: ClearResult[]): boolean {
  return results.some(result => result.status === 'would-remove' || result.status === 'would-update');
}

function printCreatedBackups(cwd: string, results: ClearResult[]): void {
  const backupPaths = [...new Set(
    results
      .filter(result => result.backupCreated && result.backupPath)
      .map(result => result.backupPath as string),
  )];
  if (backupPaths.length === 0) return;

  console.log(cli.bold('Created .bak files:'));
  for (const backupPath of backupPaths) {
    console.log(formatFileLine('neutral', path.relative(cwd, backupPath)));
  }
}

async function defaultConfirm(): Promise<boolean> {
  // Non-TTY stdin (CI, piped, /dev/null) never answers rl.question, so awaiting it
  // hangs the process to an unsettled-top-level-await exit. Decline instead of hanging.
  if (!process.stdin.isTTY) {
    console.log(
      cli.dim('\nNon-interactive stdin: declining. Re-run with --yes to apply, or --dry-run to preview.'),
    );
    return false;
  }
  const rl = createInterface({
    input: process.stdin,
    output: process.stdout,
  });
  try {
    const answer = await rl.question('\nApply these changes? [y/N] ');
    return /^(y|yes)$/iu.test(answer.trim());
  } finally {
    rl.close();
  }
}

export async function runClear(cwd: string, options: RunClearOptions = {}, invocationCwd = cwd): Promise<void> {
  const dryRun = options.dryRun === true;
  const workspaceNote = path.resolve(cwd) !== path.resolve(invocationCwd)
    ? `Workspace root: ${cwd}`
    : undefined;
  const dryRunNote = dryRun ? ' (dry run)' : '';
  console.log(`\n${formatCliBanner(cli.bold(`Clearing repovine setup${dryRunNote}`), workspaceNote)}\n`);
  console.log(cli.dim(`Preserving ${ANNOTATIONS_FILENAME}.`));
  console.log(cli.dim('Only repovine-managed sections are removed from mixed config files.\n'));

  const preview = clearWorkspace(cwd, { dryRun: true });
  printResultGroup(cwd, 'Would remove:', preview, 'would-remove', 'would-remove');
  printResultGroup(cwd, 'Would update:', preview, 'would-update', 'would-update');
  printResultGroup(cwd, 'Skipped:', preview, 'skipped', 'skipped');
  printResultGroup(cwd, 'Errors:', preview, 'error', 'error');

  if (dryRun) {
    console.log(`\n${cli.dim('No files changed.')}`);
    console.log('');
    return;
  }

  if (!hasPlannedChanges(preview)) {
    console.log(`\n${cli.dim('Nothing to clear.')}`);
    console.log('');
    return;
  }

  const confirmed = options.yes === true
    ? true
    : options.confirm
      ? await options.confirm()
      : await defaultConfirm();

  if (!confirmed) {
    console.log(`\n${cli.dim('No files changed.')}`);
    console.log('');
    return;
  }

  console.log(`\n${cli.bold('Applying repovine clear...')}\n`);
  const results = clearWorkspace(cwd, { dryRun: false });
  printResultGroup(cwd, 'Removed:', results, 'removed', 'removed');
  printResultGroup(cwd, 'Updated:', results, 'updated', 'updated');
  printResultGroup(cwd, 'Skipped:', results, 'skipped', 'skipped');
  printResultGroup(cwd, 'Errors:', results, 'error', 'error');
  printCreatedBackups(cwd, results);
  console.log('');
}
